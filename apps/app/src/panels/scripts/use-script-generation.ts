import { useCallback, useEffect, useRef, useState } from "react";

export type ScriptGeneration = {
  prompt: string;
  kind: "write" | "update";
};

export type GeneratedScript = { source: string; name: string | null };

export const STUB_GENERATION_DELAY_MS = 2000;
export const STUB_GENERATED_NAME = "AI generated script";

const stubSource = ({ prompt, kind }: ScriptGeneration, source: string) => {
  const request = prompt.replace(/\s+/g, " ").trim();
  if (kind === "update") return `// Updated by AI: ${request}\n${source}`;
  return `// This will be generated by AI.
// Request: ${request}

console.log("Script generated by AI");
`;
};

export const useScriptGeneration = () => {
  const [generation, setGeneration] = useState<ScriptGeneration | null>(null);
  const timeoutRef = useRef<ReturnType<typeof setTimeout> | null>(null);

  const clear = () => {
    if (timeoutRef.current !== null) clearTimeout(timeoutRef.current);
    timeoutRef.current = null;
  };

  const stop = useCallback(() => {
    clear();
    setGeneration(null);
  }, []);

  const generate = useCallback(
    (
      next: ScriptGeneration,
      source: string,
      onDone: (result: GeneratedScript) => void,
    ) => {
      clear();
      setGeneration(next);
      timeoutRef.current = setTimeout(() => {
        timeoutRef.current = null;
        setGeneration(null);
        onDone({
          source: stubSource(next, source),
          name: next.kind === "write" ? STUB_GENERATED_NAME : null,
        });
      }, STUB_GENERATION_DELAY_MS);
    },
    [],
  );

  useEffect(() => clear, []);

  return { generation, generate, stop };
};
